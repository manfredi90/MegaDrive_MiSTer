#!/bin/sh
# Regenerate rtl/md_core_ss.v: md_core flattened by Yosys with the savestate scan chain,
# plus rtl/md_core_ss.vh (chain length, layout hash) and the layout map
# savestate/layouts/<hash>.map.gz that the state converter needs.
# Run from anywhere after any change to rtl/md_core.v or rtl/nuked-md/*.v, and commit
# the new map. Needs yosys (tested with 0.33) and python3.
#
# Environment (for tests): OUT=dir for the .v/.vh (default rtl), DEFS="-DNAME ..." extra
# Verilog defines, MAPS=dir for the map (default savestate/layouts).
set -e
cd "$(dirname "$0")/.."
OUT=${OUT:-rtl}
MAPS=${MAPS:-savestate/layouts}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$OUT" "$MAPS"

N=rtl/nuked-md
SRC="rtl/md_core.v $N/md_board.v $N/68k.v $N/z80.v $N/fc1004.v $N/ym7101.v $N/ym6045.v $N/ym6046.v \
$N/tmss.v $N/vram.v $N/ym_lib.v $N/ym3438.v $N/ym3438_ch.v $N/ym3438_detune.v $N/ym3438_eg.v \
$N/ym3438_fsm.v $N/ym3438_io.v $N/ym3438_lfo.v $N/ym3438_op.v $N/ym3438_pg.v $N/ym3438_prescaler.v \
$N/ym3438_regs.v"

cat > "$tmp/flat.ys" <<EOF
read_verilog -lib savestate/blackbox.v
read_verilog -DEXT_CLOCKS -DM68K_CHEAT -DZ80_CHEAT $DEFS $SRC
hierarchy -check -top md_core
proc -norom
# a register copy marked dont_merge (68k.v) must not be merged here either: hide it from
# opt_merge under a cell type it does not know, Quartus then sees the mark on the reg
select -set dm a:dont_merge %ci1 t:\$dff t:\$dffe %u %i
chtype -map \$dff \$__ss_dm_dff -map \$dffe \$__ss_dm_dffe @dm
flatten
opt_clean
opt -fast
memory_collect
memory_share
opt_clean
chtype -map \$__ss_dm_dff \$dff -map \$__ss_dm_dffe \$dffe
dffunmap -srst-only
opt_clean
check
write_json $tmp/flat.json
EOF

cat > "$tmp/out.ys" <<EOF
read_json $tmp/scan.json
opt_clean
check
write_verilog $tmp/md_core_ss.v
EOF

# the "logic loop" warnings come from the Z80 and bus arbiter as written upstream
yosys -q -l "$tmp/flat.log" "$tmp/flat.ys" > /dev/null 2>&1 || { tail -20 "$tmp/flat.log"; exit 1; }
grep "^Warning" "$tmp/flat.log" | sed 's/ See .*//' | sort | uniq -c | sort -rn | head -5
# EXPERIMENT: no scan chain, area of the Yosys round trip only
python3 savestate/noscan_rename.py "$tmp/flat.json" "$tmp/scan.json"
printf "localparam SS_CHAIN_LEN = 16620;\nlocalparam [31:0] SS_LAYOUT_HASH = 32'h0;\n" > "$OUT/md_core_ss.vh"
yosys -q -l "$tmp/out.log" "$tmp/out.ys" > /dev/null 2>&1 || { tail -20 "$tmp/out.log"; exit 1; }
{
	echo "// GENERATED by savestate/gen_netlist.sh from rtl/md_core.v and rtl/nuked-md - do not edit."
	echo "// Nuked-MD: Copyright (C) 2022-2023 nukeykt, GPL-2.0-or-later (see rtl/nuked-md/LICENSE)."
	# Yosys still escapes a few names (e.g. \name_reg[7]); Quartus 17 chokes on brackets
	# inside escaped names, so make every escaped name a plain identifier. The scan-chain
	# clock enables (ss_en_*) must stay separate LUTs: Quartus would merge the identical ones.
	# Of the attributes only altera_attribute and parallel_case mean something to Quartus.
	python3 -c 'import re,sys; v=re.sub(r"\\(\S+)\s", lambda m: "esc_" + re.sub(r"\W", "_", m.group(1)) + " ", sys.stdin.read()); v=re.sub(r"(?m)^ *\(\* (init|unused_bits|top) = .*\*\)\n", "", v); sys.stdout.write(re.sub(r"(wire ss_en_\d+);", r"\1 /* synthesis keep */;", v))' < "$tmp/md_core_ss.v"
} > "$OUT/md_core_ss.v"
echo "wrote $OUT/md_core_ss.v ($(wc -c < "$OUT/md_core_ss.v") bytes)"
